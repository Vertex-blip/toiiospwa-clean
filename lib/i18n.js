export function normalizeLang(lang) {
  return LANGUAGES.some((item) => item.code === lang) ? lang : DEFAULT_LANG;
}

export function t(key, lang = DEFAULT_LANG) {
  const safeLang = normalizeLang(lang);
  return DICTIONARY[safeLang]?.[key] || DICTIONARY[DEFAULT_LANG]?.[key] || key;
}
